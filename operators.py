#arithmetic operators
x = 90
y = 5

print(x + y)
print(x - y)
print(x / y)
print(x * y)
print(x % y) #Modulus - Returns Remainder after division

#Comparison operators - Compare values and return boolean
num1 = 45
num2 = 20

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2)#equal sign always written twice
print(num1 != num2)#Not equal

#Assignment Operators - Assign/store values in variable
number = 80
print(number)

#Operator Precedence
number += 2
print(number)

#logical Operators - and, or, not
print(100==50 and 60 < 80)
print(100==50 or 60 < 80)
print(not(100==50 and 60 < 80) )


